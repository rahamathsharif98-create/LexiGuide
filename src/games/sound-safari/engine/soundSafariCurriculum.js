/**
 * In-place safe Fisher-Yates shuffle
 * Accepts an optional randomFn (e.g. for deterministic testing).
 */
export function shuffleSoundSafariOptions(options, randomFn = Math.random) {
  if (!Array.isArray(options)) return []
  const copy = [...options]
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(randomFn() * (i + 1))
    ;[copy[i], copy[j]] = [copy[j], copy[i]]
  }
  return copy
}
