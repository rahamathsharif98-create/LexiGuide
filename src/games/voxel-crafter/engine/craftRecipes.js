export function getCraftRecipe(index = 0) {
  return CRAFT_RECIPES[index % CRAFT_RECIPES.length];
}

export function getStageForLevel(level = 1) {
  const safeLevel = Math.max(1, Math.min(level, CRAFT_RECIPES.length));
  return VOXEL_STAGES.find((s) => s.levels.includes(safeLevel)) || VOXEL_STAGES[0];
}
